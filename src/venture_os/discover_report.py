"""Render Discover results to outputs/ (CLAUDE.md naming) through venture_os.outputs.write_output.

phase1_step1_brief, phase1_step2_opportunities, phase1_step3_idea_scores, phase1_step4_market,
phase1_step5_interview_plan (.md + .json each) and phase1_gate_decision (.md + .json).
Only real runs write here. Every market claim shows its URL and dates or is labelled ASSUMPTION.
"""

from __future__ import annotations

import json

from venture_os.outputs import write_output


def _esc(s) -> str:
    return str(s or "").replace("|", "\\|").replace("\n", " ").strip()


def _head(title: str, run_id: str, research: dict) -> list[str]:
    b = research.get("brief") or {}
    models = research.get("models") or {}
    used = ", ".join(f"{k}: {v}" for k, v in models.items() if v) or "none (rules only, LLM_MODE not live)"
    return [f"# {title}", "", (f"Run `{run_id}` · brief `{b.get('brief_id')}` v{b.get('version')} · generated by the "
                              f"Discover pipeline · models: {used}"), ""]


def _claim_line(c: dict) -> str:
    return (f"> {_esc(c.get('quote'))[:400]}\n>\n> — [{_esc(c.get('title'))[:70] or c['url']}]({c['url']}) · "
            f"published {c.get('published_at') or 'undated'} · retrieved {(c.get('retrieved_at') or '')[:10]}"
            f" · `{c['id']}`" + (f" · flags: {', '.join(c['flags'])}" if c.get("flags") else ""))


def _write(step: int | None, name: str, lines: list[str], data: dict, gate: bool = False) -> list[str]:
    md = write_output(1, step, name, "\n".join(lines).rstrip() + "\n", gate=gate)
    js = write_output(1, step, name, json.dumps(data, ensure_ascii=False, indent=1, default=str) + "\n", ext="json",
                      gate=gate)
    return [str(md), str(js)]


def write_all(run_id: str, output: dict) -> list[str]:
    r = output.get("research") or {}
    written = []
    b = r.get("brief") or {}
    pt = b.get("product_type") or {}
    lines = _head("Discover step 1 - The founder brief", run_id, r)
    lines += ["| Field (official brief) | Value |", "|---|---|"]
    lines += [f"| {k} | {_esc(v) if v else '**unknown** (never filled in)'} |" for k, v in (b.get("required") or {}).items()]
    lines += ["", (f"**Product type:** {pt.get('label')} ({pt.get('group')}) · decided by {pt.get('decided_by')} · "
                  f"trigger: {_esc(pt.get('trigger'))}")]
    if pt.get("clarifying_question"):
        lines.append(f"**Question for the founder:** {pt['clarifying_question']}")
    lines += ["", f"Unknown fields: {', '.join(b.get('unknown') or []) or 'none'}"]
    if b.get("open_questions"):
        lines += ["", "Research questions from onboarding:", *[f"- {q}" for q in b["open_questions"]]]
    written += _write(1, "brief", lines, b)

    claims = {c["id"]: c for c in r.get("claims") or []}
    ideas = r.get("ideas") or []
    if ideas or r.get("claims"):
        lines = _head("Discover step 2 - Opportunities (core step: find opportunities)", run_id, r)
        for i in ideas:
            lines += [f"## {i['id']} · {_esc(i['title'])}", "",
                      (f"*{'Starting idea (sharpened)' if i['origin'] == 'starting_idea' else 'Alternative'}* · "
                      f"{i['product_type']} · built by {i['built_by']}"), "", _esc(i["description"]), "",
                      f"**Pain it solves:** {_esc(i['pain'])}", f"**Why this founder:** {_esc(i['why_founder'])}", ""]
            cited = [claims[c] for c in i["pain_claim_ids"] if c in claims]
            if i["origin"] == "alternative" and cited and i["pain_claim_ids"] == ideas[0]["pain_claim_ids"]:
                lines += [(f"Pain evidence: the same quotes as {ideas[0]['id']} ({', '.join(i['pain_claim_ids'][:6])});"
                          " they are about the problem, not this format."), ""]
            else:
                lines += [_claim_line(c) + "\n" for c in cited[:4]] or [
                    "**ASSUMPTION:** no quote from a real person yet.", ""]
            lines += [f"- {a}" for a in i.get("assumptions") or []] + [""]
        pain = [c for c in r.get("claims") or [] if c["topic"] == "pain"]
        lines += ["## All pain quotes found", ""] + [_claim_line(c) + "\n" for c in pain[:20]]
        if not pain:
            lines.append("No quotes found: the problem is an **ASSUMPTION** until people are found describing it.")
        written += _write(2, "opportunities", lines, {"ideas": ideas, "pain_claims": pain})

    scores = r.get("scores") or []
    if scores:
        crit = [c["criterion"] for c in scores[0]["criteria"]]
        lines = _head("Discover step 3 - Idea scores", run_id, r)
        lines += [("Scores 1-5 per criterion; totals are computed in plain code from config/gates/discover.yaml. A "
                  "score without evidence is capped and marked ASSUMPTION (A)."), "",
                  "| Idea | " + " | ".join(crit) + " | **Total** |", "|---|" + "---|" * (len(crit) + 1)]
        for s in scores:
            cells = [f"{c['score']:g}" + (" (A)" if c["basis"] == "ASSUMPTION" else "") for c in s["criteria"]]
            lines.append(f"| {s['idea_id']} | " + " | ".join(cells) + f" | **{s['total']}** |")
        lines += ["", "## Evidence and notes per score", ""]
        for s in scores:
            lines.append(f"**{s['idea_id']}** (proposed by {s['proposed_by']})")
            lines += [f"- {c['criterion']}: {c['score']:g} - {_esc(c['note'])}" +
                      (f" · evidence: {', '.join(c['evidence_ids'])}" if c["evidence_ids"] else " · **ASSUMPTION**")
                      for c in s["criteria"]]
            lines.append("")
        written += _write(3, "idea_scores", lines, {"scores": scores})

    m = r.get("market")
    if m:
        lines = _head("Discover step 4 - Market", run_id, r)
        lines += [f"**Segment:** {_esc(m['segment'])}", f"**Geography:** {_esc(m['geography'])}",
                  f"**Beachhead:** {_esc(m['beachhead'])}", "", "## Competitors and substitutes", "",
                  "| Name | Kind | Price | Signal | Source |", "|---|---|---|---|---|"]
        for c in m["competitors"]:
            price = _esc(c.get("price")) + (f" (`{c['price_claim_id']}`)" if c.get("price_claim_id") else "") \
                if c.get("price") else "no sourced price"
            lines.append(f"| {_esc(c['name'])[:60]} | {c['kind']} | {price} | {_esc(c.get('signal'))[:40]} | "
                         f"[link]({c['url']}) |")
        if not m["competitors"]:
            lines.append("| none found | | | | warning: 0 competitors is not a pass |")

        def rng(x):
            lo, hi = x
            return "unknown" if lo is None or hi is None else f"{lo:,.0f} - {hi:,.0f} {m['currency']}"
        lines += ["", "## Bottom-up sizing", "", f"`{m['formula']}`", "", "| Input | Low | High | Unit | Basis |",
                  "|---|---|---|---|---|"]
        for i in m["inputs"]:
            basis = f"sourced (`{i['claim_id']}`)" if i["basis"] == "sourced" else "**ASSUMPTION**"
            lines.append(f"| {i['name']} | {i['low'] if i['low'] is not None else '?'} | "
                         f"{i['high'] if i['high'] is not None else '?'} | {i['unit']} | {basis}: {_esc(i['note'])[:120]} |")
        lines += ["", f"**TAM:** {rng(m['tam'])} · **SAM:** {rng(m['sam'])} · **SOM:** {rng(m['som'])}", ""]
        lines += [f"> {n}" for n in m.get("notes") or []]
        priced = [claims[c["price_claim_id"]] for c in m["competitors"] if c.get("price_claim_id") in claims]
        if priced:
            lines += ["", "## Price evidence", ""] + [_claim_line(c) + "\n" for c in priced[:12]]
        written += _write(4, "market", lines, m)

    ip = r.get("interview_plan")
    if ip:
        lines = _head("Discover step 5 - Interview plan (The Mom Test)", run_id, r)
        lines += [f"**Who:** {_esc(ip['who'])}", f"**How many:** {ip['how_many']}", "", "**Where to find them:**",
                  *[f"- {w}" for w in ip["where_to_find"]], ""]
        lines += [f"> {a}" for a in ip.get("assumptions") or []]
        for lang, g in ip["guides"].items():
            lines += ["", f"## Questions ({lang})", "", *[f"{n}. {q}" for n, q in enumerate(g["questions"], 1)], "",
                      "Avoid:", *[f"- {a}" for a in g["avoid"]]]
        rejected = [x for x in ip.get("lint") or [] if not x["ok"]]
        lines += ["", (f"Script linter: {len(ip.get('lint') or [])} questions checked, {len(rejected)} rejected and "
                      "rewritten (rules in prompts/interview_designer.md).")]
        lines += ["", "## Notes form", "", *[f"- {f}" for f in ip["notes_form"]], "", f"**{ip['results_rule']}**", ""]
        ivs = r.get("interviews") or []
        lines.append(f"## Interviews entered by the founder: {len(ivs)}")
        if not ivs:
            lines.append("None entered yet. The system never writes interview answers.")
        for iv in ivs:
            lines.append(f"- {_esc(iv['person'])}: counts as evidence: {iv['counts']}, past behaviour: "
                         f"{iv['past_behaviour']}")
        lines += ["", "Method: " + ", ".join(f"[{s['title']}]({s['url']})" for s in ip["method_sources"])]
        written += _write(5, "interview_plan", lines, {**ip, "interviews": ivs})

    written += write_gate(run_id, r)
    return written


def write_gate(run_id: str, research: dict, decision: dict | None = None) -> list[str]:
    gate = research.get("gate") or {}
    lines = _head("Discover gate decision", run_id, research)
    lines += [f"**System recommendation: {str(gate.get('recommendation', 'n/a')).upper()}**"
              + (f" → pivot to `{gate['pivot_to']}`" if gate.get("pivot_to") else "") + " (the founder decides)", "",
              *[f"- {x}" for x in gate.get("reasons") or []], "",
              "| Check | Target (set before the run) | Actual | Passed |", "|---|---|---|---|"]
    lines += [f"| {c['check']} | {c['target']} | {c['actual']} | {'yes' if c['passed'] else 'no'} |"
              for c in gate.get("checks") or []]
    if gate.get("collect_next"):
        lines += ["", "**To collect before running again:**", *[f"- {x}" for x in gate["collect_next"]]]
    critic = research.get("critic") or {}
    if critic:
        lines += ["", "## Research critic", "", f"Model review: {critic.get('model_review')}"
                  + (f" (judge: {critic['judge_model']})" if critic.get("judge_model") else ""), ""]
        lines += [f"- **{f['kind']}**: {_esc(f['detail'])}" + (f" ({', '.join(f['claim_ids'])})" if f.get("claim_ids") else "")
                  for f in critic.get("findings") or []]
    lines += ["", "## Founder decision", ""]
    if decision:
        lines += [f"**{decision['decision']}** (outcome: **{decision['outcome']}**) by the founder",
                  f"Note: {_esc(decision.get('note')) or '-'}"]
        if decision.get("pivot_to"):
            lines.append(f"Pivot to: {decision['pivot_to']}")
        if decision.get("waiver_reason"):
            lines.append(f"Waiver reason: {_esc(decision['waiver_reason'])}")
    else:
        lines.append("Waiting for the founder's decision (go / repeat / pivot / stop / waive with reason).")
    return _write(None, "decision", lines, {"gate": gate, "critic": critic, "decision": decision}, gate=True)
